namespace {
    bool sameTrimValue(double a, double b) { return std::memcmp(&a, &b, sizeof(a)) == 0; }
    bool sameTrimValue(const RS_Vector& a, const RS_Vector& b) {
        return a.valid == b.valid && sameTrimValue(a.x, b.x) && sameTrimValue(a.y, b.y) && sameTrimValue(a.z, b.z);
    }
    bool sameTrimOptions(const LC_StoredCacheTrimOptions& a, const LC_StoredCacheTrimOptions& b) {
        const auto& x = a.kernel; const auto& y = b.kernel;
        return std::tie(x.maxSpansPerCurve, x.maxInputSpans, x.maxInputRecords, x.maxBoxPairs, x.maxLeaves,
            x.maxGeneratedItems, x.maxOrderingComparisons, x.maxRoots, x.maxDepth, x.maxLeafDepth, x.maxFragments,
            x.maxOutputSpans, x.maxOutputControls, x.maxOutputKnots, a.maxOutputEntities, a.maxDisplayEntities,
            a.cancellation.requested) ==
            std::tie(y.maxSpansPerCurve, y.maxInputSpans, y.maxInputRecords, y.maxBoxPairs, y.maxLeaves,
            y.maxGeneratedItems, y.maxOrderingComparisons, y.maxRoots, y.maxDepth, y.maxLeafDepth, y.maxFragments,
            y.maxOutputSpans, y.maxOutputControls, y.maxOutputKnots, b.maxOutputEntities, b.maxDisplayEntities,
            b.cancellation.requested);
    }
    bool isTrimTarget(const RS_Entity* entity, bool allowCacheSpline = false) {
        return entity != nullptr && (entity->rtti() == RS2::EntityOffsetCurve || entity->isAtomic() ||
            (allowCacheSpline && entity->rtti() == RS2::EntitySpline)) &&
            (entity->getParent() == nullptr || entity->getParent()->rtti() != RS2::EntityOffsetCurve);
    }

    RS_Entity* nativeLimitOwner(RS_Entity* entity) {
        if (entity != nullptr && entity->getParent() != nullptr &&
            entity->getParent()->rtti() == RS2::EntityOffsetCurve) {
            auto* owner = entity->getParent();
            if (!owner->isOwner() || owner->size() > kDefaultOffsetDeepEntitiesPerSource ||
                std::find(owner->begin(), owner->end(), entity) == owner->end()) return nullptr;
            return owner;
        }
        return entity;
    }
}

struct LC_ActionModifyTrim::NativeTrimWork {
    RS_Document* document = nullptr;
    RS_Entity *target = nullptr, *limit = nullptr;
    RS_Vector targetPick, limitPick, zero, markedZero;
    std::array<RS_Vector, 3> world, screen;
    double angle = 0;
    bool counterClockwise = true, detached = false;
    int status = 0;
    std::uint64_t epoch = 0;
    QList<RS_Entity*> selection;
    LC_StoredCacheTrimOptions options;
    QElapsedTimer elapsed;
    std::shared_ptr<LC_OffsetCreationSources> inputs;
    std::unique_ptr<LC_OffsetTrimWorker::Prepared> prepared;
};

struct LC_ActionModifyTrim::TrimActionData {
    RS_Vector limitCoord;
    RS_Vector trimCoord;
    // the limit, when it is generated by another entity, see setLimitEntity()
    std::unique_ptr<RS_Entity> limitCopy;
    unsigned long long limitId = 0;
    unsigned long long trimId = 0;
    std::size_t demoted = 0;
    std::uint64_t undoEpoch = 0;
    std::optional<std::uint64_t> triggerAdmissionEpoch;
    std::unique_ptr<LC_OffsetTrimWorker> worker;
    std::unique_ptr<QTimer> guard;
    std::shared_ptr<NativeTrimWork> work;
};

/**
 * @param actionContext
 * @param both Trim both entities.
 */
LC_ActionModifyTrim::LC_ActionModifyTrim(LC_ActionContext* actionContext, const bool both)
    : LC_UndoableDocumentModificationAction(both ? "ActionModifyTrim2" : "ActionModifyTrim", actionContext, both ? RS2::ActionModifyTrim2 : RS2::ActionModifyTrim),
      m_actionData(std::make_unique<TrimActionData>()), m_both{both} {
    m_actionData->worker = std::make_unique<LC_OffsetTrimWorker>();
    m_actionData->guard = std::make_unique<QTimer>();
    m_actionData->guard->setInterval(25);
    connect(m_actionData->guard.get(), &QTimer::timeout, this, [this] {
        const auto work = m_actionData->work;
        if (!work) return;
        const QPointer<LC_ActionModifyTrim> alive(this);
        try {
            const bool timedOut = work->elapsed.elapsed() >= LC_OffsetWorkerClient::Deadlines::commit;
            const bool current = !timedOut && currentNativeTrim(work);
            if (alive && !current) {
                cancelNativeTrim();
                if (currentTrimContext()) commandMessage(timedOut ? tr("Trim worker timed out; nothing changed") :
                    tr("Trim inputs changed; nothing changed"));
            }
        } catch (...) { if (alive) cancelNativeTrim(); }
    });
    m_liveTrimView = m_graphicView;
    if (m_document) m_document->getSelection()->addListener(this);
    if (m_liveTrimView) connect(m_liveTrimView.data(), &QObject::destroyed, this, [this] {
        abandonTrimContext(false);
    });
}

LC_ActionModifyTrim::~LC_ActionModifyTrim() {
    cancelNativeTrim();
    if (!currentTrimContext()) abandonTrimContext(true);
    if (m_liveTrimView) disconnect(m_liveTrimView.data(), nullptr, this, nullptr);
}

void LC_ActionModifyTrim::selectedSetDestroyed() {
    // The tracked registration is already removed; do not read the dying document.
    abandonTrimContext(true);
}

bool LC_ActionModifyTrim::currentTrimContext() const {
    return m_actionContext && m_document && m_liveTrimView && !m_liveTrimView->isClosing() &&
        m_liveTrimView.data() == m_graphicView && m_actionContext->getDocument() == m_document &&
        m_actionContext->getGraphicView() == m_liveTrimView.data() &&
        m_liveTrimView->getViewPort() == m_viewport && m_liveTrimView->getDocument() == m_document &&
        m_document->isOwner() && m_document->size() <= (std::size_t{1} << 20);
}

void LC_ActionModifyTrim::abandonTrimContext(const bool viewportMayBeAlive) {
    cancelNativeTrim();
    // Existing overlay containers only: no lazy allocation or redraw through a stale context.
    auto* viewport = viewportMayBeAlive && m_liveTrimView && m_liveTrimView.data() == m_graphicView &&
        m_liveTrimView->getViewPort() == m_viewport ? m_viewport : nullptr;
    if (viewport) {
        viewport->clearOverlayEntitiesContainer(RS2::ActionPreviewEntity);
        viewport->clearOverlayEntitiesContainer(RS2::OverlayEffects);
        for (const auto overlay : {RS2::ActionPreviewEntity, RS2::OverlayEffects, RS2::Snapper, RS2::InfoCursor})
            viewport->clearOverlayDrawablesContainer(overlay);
    }
    m_trimEntity = m_limitEntity = nullptr;
    m_actionData->trimId = m_actionData->limitId = 0;
    m_actionData->limitCopy.reset(); m_actionData->demoted = 0;
    if (m_preview) { m_preview->setParent(nullptr); m_preview->clear(); }
    for (auto* entity : *m_highlight) { entity->setParent(nullptr); entity->clearSelectionFlag(); }
    m_highlight->clear(); m_hasPreview = false;
    m_visualSnapManager->detachFromView();
    m_document = nullptr; m_graphic = nullptr; m_keyEntity = nullptr;
    m_graphicView = nullptr; m_viewport = nullptr; m_formatter = nullptr; m_infoCursorOverlayPrefs = nullptr;
    m_finished = true;
    setFinished();
}

RS_Entity* LC_ActionModifyTrim::mappedTrimPick(const RS_Entity* address, const bool allowNestedLimit) const {
    if (!address || !currentTrimContext()) return nullptr;
    constexpr std::size_t cap = std::size_t{1} << 20;
    const int direct = m_document->findEntityIndex(address);
    if (direct >= 0) {
        auto* entity = m_document->entityAt(direct);
        if (!entity || entity->getParent() != m_document || entity->isDeleted()) return nullptr;
        if (entity->rtti() == RS2::EntityOffsetCurve) {
            const auto* native = dynamic_cast<const LC_OffsetCurve*>(entity);
            if (!native || !native->isOwner()) return nullptr;
        }
        return entity;
    }
    // Compare saved child addresses only while walking live, owned containers.
    // The immediate owning container, not a child's arbitrary parent pointer,
    // establishes the mapping. Native children may only map to a direct owner.
    std::vector<RS_EntityContainer*> pending;
    std::size_t work = 0;
    for (auto* root : *m_document) {
        if (++work > cap) return nullptr;
        if (!root || root->getParent() != m_document || root->isDeleted()) continue;
        auto* container = dynamic_cast<RS_EntityContainer*>(root);
        if (!container || !container->isOwner() || container->size() > cap) continue;
        if (container->rtti() == RS2::EntityOffsetCurve) {
            if (!dynamic_cast<LC_OffsetCurve*>(container)) continue;
            for (auto* child : *container) {
                if (++work > cap) return nullptr;
                if (child == address) return child && child->getParent() == container && !child->isDeleted() ? root : nullptr;
            }
        } else if (allowNestedLimit) pending.push_back(container);
    }
    while (!pending.empty()) {
        auto* container = pending.back(); pending.pop_back();
        for (auto* child : *container) {
            if (++work > cap) return nullptr;
            if (!child || child->getParent() != container || child->isDeleted()) continue;
            // A native nested in an INSERT/group is never an explicit native limit.
            if (child->rtti() == RS2::EntityOffsetCurve) continue;
            if (child == address) return child;
            auto* nested = dynamic_cast<RS_EntityContainer*>(child);
            if (nested && nested->isOwner() && nested->size() <= cap) pending.push_back(nested);
        }
    }
    return nullptr;
}

void LC_ActionModifyTrim::mouseMoveEvent(QMouseEvent* event) {
    if (hasPendingNativeTrim()) return;
    if (!validateCapturedTrimInputs()) return;
    RS_PreviewActionInterface::mouseMoveEvent(event);
}

void LC_ActionModifyTrim::mousePressEvent(QMouseEvent* event) {
    if (hasPendingNativeTrim()) return;
    if (!validateCapturedTrimInputs()) return;
    RS_ActionInterface::mousePressEvent(event);
}

void LC_ActionModifyTrim::mouseReleaseEvent(QMouseEvent* event) {
    if (hasPendingNativeTrim() && event->button() != Qt::RightButton) return;
    if (hasPendingNativeTrim()) cancelNativeTrim();
    if (!validateCapturedTrimInputs()) return;
    RS_ActionInterface::mouseReleaseEvent(event);
}

void LC_ActionModifyTrim::init(const int status) {
    cancelNativeTrim();
    if (!currentTrimContext()) { abandonTrimContext(true); return; }
    if (mayInitWithContextEntity(status)) {
        const auto* saved = m_actionContext->getContextMenuActionContextEntity();
        if (saved && !mappedTrimPick(saved, false))
            m_actionContext->saveContextMenuActionContext(nullptr, RS_Vector(false), false);
    }
    if (status == ChooseLimitEntity) {
        m_trimEntity = m_limitEntity = nullptr;
        m_actionData->trimId = m_actionData->limitId = 0;
        m_actionData->limitCopy.reset();
    }
    m_snapMode.clear();
    m_snapMode.restriction = RS2::RestrictNothing;
    RS_PreviewActionInterface::init(status);
}

void LC_ActionModifyTrim::doInitWithContextEntity(RS_Entity* contextEntity, const RS_Vector& clickPos) {
    contextEntity = mappedTrimPick(contextEntity, false);
    if (isTrimTarget(contextEntity, hasNativeTrimPartner())) {
        m_trimEntity = contextEntity;
        m_actionData->trimId = contextEntity->getId();
        m_actionData->trimCoord = clickPos;
        m_actionData->undoEpoch = m_document->undoStateEpoch();
    }
}

void LC_ActionModifyTrim::finish() {
    cancelNativeTrim();
    if (!currentTrimContext()) { abandonTrimContext(true); return; }
    RS_PreviewActionInterface::finish();
}

void LC_ActionModifyTrim::suspend() {
    cancelNativeTrim();
    if (currentTrimContext()) RS_PreviewActionInterface::suspend();
}

void LC_ActionModifyTrim::keyPressEvent(QKeyEvent* event) {
    if (hasPendingNativeTrim() && event->key() == Qt::Key_Escape) {
        cancelNativeTrim(); event->accept(); return;
    }
    if (currentTrimContext()) RS_PreviewActionInterface::keyPressEvent(event);
    else event->accept();
}

/**
 * The entity a click picks as the limit, or as the first entity of Trim Two; nullptr if there is none.
 */
RS_Entity* LC_ActionModifyTrim::catchLimitEntity(const LC_MouseEvent* e) const {
    if (m_both) {
        // Trim Two replaces this entity by a trimmed copy in the drawing, as it does the second one, so
        // like the second one it must be an atomic entity of the drawing itself: not a segment of a
        // polyline, nor a line of a spline, a block reference or a dimension
        RS_Entity* entity = nativeLimitOwner(catchEntityByEvent(e, RS2::ResolveNone));
        return isTrimTarget(entity, hasNativeTrimPartner()) ? entity : nullptr;
    }
    RS_Entity* entity = catchEntityByEvent(e, RS2::ResolveAllButTextImage);
    // the lines a spline is drawn with only approximate it: the curve is the limit, not the line clicked
    if (entity != nullptr && entity->getParent() != nullptr && entity->getParent()->rtti() == RS2::EntitySpline) {
        entity = entity->getParent();
    }
    return nativeLimitOwner(entity);
}

/**
 * The owners of entities that are not editable (see RS_Information::isEditable()) rebuild them, and so free
 * them, whenever they are updated, as all block references are when a layer is shown or hidden or an edit is
 * redone. A limit the action keeps between clicks is therefore a copy of such an entity, apart from the drawing.
 */
void LC_ActionModifyTrim::setLimitEntity(RS_Entity* entity) {
    entity = mappedTrimPick(entity, !m_both);
    if (entity && entity->rtti() == RS2::EntityOffsetCurve && entity->getParent() != m_document) entity = nullptr;
    if (m_both && !isTrimTarget(entity, hasNativeTrimPartner())) entity = nullptr;
    if (entity == m_limitEntity) {
        return;
    }
    std::unique_ptr<RS_Entity> preparedCopy;
    if (entity != nullptr && (!RS_Information::isEditable(entity) || entity->getParent() != m_document)) {
        // One-sided ordinary subentities remain usable even if their owner is
        // subsequently rebuilt or deleted. Never retain a borrowed child address.
        std::unique_ptr<RS_Entity> copy(entity->clone());
        if (!copy) { m_limitEntity = nullptr; m_actionData->limitId = 0; m_actionData->limitCopy.reset(); return; }
        copy->setPen(entity->getPen(true));
        copy->setLayer(nullptr);
        copy->setParent(nullptr);
        entity = copy.get();
        preparedCopy = std::move(copy);
    }
    m_limitEntity = entity;
    m_actionData->limitId = entity ? entity->getId() : 0;
    m_actionData->limitCopy.swap(preparedCopy);
    if (entity) m_actionData->undoEpoch = m_document->undoStateEpoch();
}

bool LC_ActionModifyTrim::capturedTrimInputsLive() const {
    if (!currentTrimContext()) return false;
    if ((m_trimEntity || m_limitEntity) && m_actionData->undoEpoch != m_document->undoStateEpoch()) return false;
    const auto live = [&](const RS_Entity* address, unsigned long long id) {
        if (!address) return true;
        // Only the action's private limit copy may be outside the document.
        // All other retained addresses are compared before their first getter.
        if (address == m_actionData->limitCopy.get()) return address->getId() == id;
        if (m_document->findEntityIndex(address) < 0) return false;
        return address->getId() == id && address->getParent() == m_document && !address->isDeleted();
    };
    return live(m_trimEntity, m_actionData->trimId) && live(m_limitEntity, m_actionData->limitId);
}

bool LC_ActionModifyTrim::validateCapturedTrimInputs() {
    if (!currentTrimContext()) { abandonTrimContext(true); return false; }
    if (capturedTrimInputsLive()) return true;
    m_trimEntity = nullptr; m_limitEntity = nullptr;
    m_actionData->trimId = m_actionData->limitId = 0;
    m_actionData->limitCopy.reset(); m_actionData->demoted = 0;
    // Private preview ownership is released even when the view changed.
    m_preview->clear();
    if (currentTrimContext()) {
        deletePreviewAndHighlights();
        setStatus(ChooseLimitEntity);
    }
    commandMessage(tr("Trim refused: a stored source is no longer live in this editable document; nothing changed"));
    return false;
}

bool LC_ActionModifyTrim::hasPendingNativeTrim() const noexcept { return bool(m_actionData->work); }

void LC_ActionModifyTrim::cancelNativeTrim() {
    m_actionData->work.reset();
    if (m_actionData->guard) m_actionData->guard->stop();
    if (m_actionData->worker) m_actionData->worker->cancel();
}

bool LC_ActionModifyTrim::currentNativeTrim(const std::shared_ptr<NativeTrimWork>& work) const {
    if (m_actionData->work != work || !currentTrimContext() || m_document != work->document ||
        !capturedTrimInputsLive() || m_document->undoStateEpoch() != work->epoch ||
        work->elapsed.elapsed() >= LC_OffsetWorkerClient::Deadlines::commit ||
        m_trimEntity != work->target || m_limitEntity != work->limit || getStatus() != work->status ||
        !sameTrimValue(m_actionData->trimCoord, work->targetPick) ||
        !sameTrimValue(m_actionData->limitCoord, work->limitPick)) return false;
    const QPointer<const LC_ActionModifyTrim> alive(this);
    const auto options = storedCacheTrimOptions();
    if (!alive || !sameTrimOptions(options, work->options) ||
        (options.cancellation.requested && options.cancellation.requested->load(std::memory_order_relaxed))) return false;
    auto selection = m_document->getSelection()->begin();
    for (auto* entity : work->selection) {
        if (selection == m_document->getSelection()->end() || *selection != entity) return false;
        ++selection;
    }
    if (selection != m_document->getSelection()->end()) return false;
    const std::array<RS_Vector, 3> world{m_viewport->toWorld({0, 0}), m_viewport->toWorld({1, 0}), m_viewport->toWorld({0, 1})};
    const std::array<RS_Vector, 3> screen{m_viewport->toWorldFromUi(0, 0), m_viewport->toWorldFromUi(1, 0), m_viewport->toWorldFromUi(0, 1)};
    for (std::size_t i = 0; i < world.size(); ++i)
        if (!sameTrimValue(world[i], work->world[i]) || !sameTrimValue(screen[i], work->screen[i])) return false;
    if (!sameTrimValue(m_viewport->getRelativeZero(), work->zero) ||
        !sameTrimValue(m_viewport->getMarkedRelativeZero(), work->markedZero) ||
        !sameTrimValue(m_viewport->toWorldAngle(m_viewport->toAbsUCSAngle(0)), work->angle) ||
        m_viewport->areAnglesCounterClockwise() != work->counterClockwise) return false;
    if (work->detached) {
        if (m_actionData->limitCopy.get() != work->limit) return false;
        return work->inputs->matchesDetached(*m_document, m_actionData->limitCopy.get());
    }
    return work->inputs->matches(*m_document);
}

void LC_ActionModifyTrim::beginNativeTrim() {
    const QPointer<LC_ActionModifyTrim> alive(this);
    try {
        QElapsedTimer elapsed; elapsed.start();
        if (!validateCapturedTrimInputs() || !m_trimEntity || !m_limitEntity || m_trimEntity == m_limitEntity ||
            m_document->undoStateEpoch() >= std::uint64_t(std::numeric_limits<qint64>::max())) return;
        auto work = std::make_shared<NativeTrimWork>();
        work->elapsed = elapsed;
        work->document = m_document; work->target = m_trimEntity; work->limit = m_limitEntity;
        work->targetPick = m_actionData->trimCoord; work->limitPick = m_actionData->limitCoord;
        work->status = getStatus(); work->epoch = m_document->undoStateEpoch();
        work->detached = m_actionData->limitCopy.get() == m_limitEntity;
        work->options = storedCacheTrimOptions(); if (!alive) return;
        for (auto* selected : *m_document->getSelection()) {
            if (work->selection.size() == 4096) throw std::length_error("Trim selection exceeded");
            work->selection.append(selected);
        }
        work->world = {m_viewport->toWorld({0, 0}), m_viewport->toWorld({1, 0}), m_viewport->toWorld({0, 1})};
        work->screen = {m_viewport->toWorldFromUi(0, 0), m_viewport->toWorldFromUi(1, 0), m_viewport->toWorldFromUi(0, 1)};
        work->zero = m_viewport->getRelativeZero(); work->markedZero = m_viewport->getMarkedRelativeZero();
        work->angle = m_viewport->toWorldAngle(m_viewport->toAbsUCSAngle(0));
        work->counterClockwise = m_viewport->areAnglesCounterClockwise();
        work->inputs = work->detached ? LC_OffsetCreationSources::captureDetachedLimit(*m_document, *work->target, *work->limit) :
            LC_OffsetCreationSources::capture(*m_document, {work->target, work->limit});
        if (!work->inputs || work->inputs->sources().size() != 2 || work->inputs->originals().size() != 2 ||
            work->inputs->originals()[0] != work->target || work->inputs->originals()[1] != work->limit)
            throw std::runtime_error("Trim input snapshot refused");
        m_actionData->work = work;
        if (!currentNativeTrim(work)) throw std::runtime_error("Trim input changed");
        auto target = work->inputs->cloneWorkerSource(0), limit = work->inputs->cloneWorkerSource(1);
        if (!target || !limit || !m_actionData->worker->start(std::move(target), work->targetPick,
            std::move(limit), work->limitPick, m_both, work->options.kernel, qint64(work->epoch), qint64(work->epoch),
            LC_OffsetWorkerClient::Mode::Commit, [alive, work](LC_OffsetTrimWorker::Outcome result) {
                if (!alive || alive->m_actionData->work != work) return;
                if (result.status != LC_OffsetTrimWorker::Status::Completed || !result.prepared) {
                    alive->cancelNativeTrim();
                    if (alive->currentTrimContext()) alive->commandMessage(result.status == LC_OffsetTrimWorker::Status::TimedOut ?
                        tr("Trim worker timed out; nothing changed") : tr("Offset cache trim worker failed; nothing changed"));
                    return;
                }
                work->prepared = std::move(result.prepared);
                try { alive->completeNativeTrim(work); }
                catch (...) {
                    if (alive) { alive->cancelNativeTrim(); if (alive->currentTrimContext()) alive->commandMessage(tr("Offset cache trim preparation failed; nothing changed")); }
                }
            })) throw std::runtime_error("Trim worker admission refused");
        m_actionData->guard->start();
    } catch (...) {
        if (!alive) return;
        cancelNativeTrim();
        if (currentTrimContext()) commandMessage(tr("Offset cache trim preparation failed; nothing changed"));
    }
}

void LC_ActionModifyTrim::completeNativeTrim(const std::shared_ptr<NativeTrimWork>& work) {
    const QPointer<LC_ActionModifyTrim> alive(this);
    if (!currentNativeTrim(work)) {
        if (alive) { cancelNativeTrim(); if (currentTrimContext()) commandMessage(tr("Trim inputs changed; nothing changed")); }
        return;
    }
    const auto receipt = work->prepared->completions(work->epoch);
    if (!receipt) throw std::runtime_error("Trim completion missing");
    LC_DocumentModificationBatch batch;
    const auto result = RS_Modification::trimStoredCachePrepared(*m_document, *work->target, work->targetPick,
        *work->limit, work->limitPick, m_both, batch, *receipt, work->options);
    std::array<std::unique_ptr<RS_Entity>, 4> owners;
    if (batch.entitiesToAdd.size() > qsizetype(owners.size())) {
        for (auto* entity : std::as_const(batch.entitiesToAdd)) delete entity;
        throw std::runtime_error("Trim output exceeded");
    }
    for (qsizetype i = 0; i < batch.entitiesToAdd.size(); ++i) owners[std::size_t(i)].reset(batch.entitiesToAdd[i]);
    if (!alive) return;
    if (!result.result) {
        QString reason;
        using Refusal = LC_OffsetCacheTrim::Refusal;
        switch (result.cacheRefusal.value_or(Refusal::InvalidInput)) {
        case Refusal::NoUsableRoots: reason = tr("no usable intersections"); break;
        case Refusal::AmbiguousPick: reason = tr("ambiguous picked interval"); break;
        case Refusal::AmbiguousRoots: case Refusal::TangencyOrOverlap: reason = tr("uncertain, tangent or overlapping intersections"); break;
        case Refusal::LimitExceeded: reason = tr("work or output limit reached"); break;
        case Refusal::Cancelled: reason = tr("cancelled"); break;
        case Refusal::UnsupportedLayout: reason = tr("target is locked, hidden, stale or unsupported"); break;
        case Refusal::UnsupportedCutter: reason = tr("unsupported limiting geometry"); break;
        case Refusal::AllocationFailure: reason = tr("not enough memory"); break;
        default: reason = tr("invalid or unresolved geometry"); break;
        }
        cancelNativeTrim();
        if (currentTrimContext()) commandMessage(tr("Offset cache trim refused: %1; nothing changed").arg(reason));
        return;
    }
    if (!currentNativeTrim(work)) { if (alive) cancelNativeTrim(); return; }
    std::set<quint32> handles;
    std::set<unsigned long long> lineages;
    for (auto* entity : std::as_const(batch.entitiesToDelete)) {
        if (entity->sourceHandle()) handles.insert(entity->sourceHandle());
        if (entity->rtti() == RS2::EntityInsert || entity->ownerLineage()) lineages.insert(entity->lineage());
    }
    std::map<unsigned long long, int> copies;
    std::map<std::pair<unsigned long long, int>, unsigned long long> copiedLineages;
    const auto copied = [&](unsigned long long original, int number) {
        auto& value = copiedLineages[{original, number}]; if (!value) value = RS_Entity::newLineage(); return value;
    };
    for (auto* entity : std::as_const(batch.entitiesToAdd)) {
        if (!entity->sourceHandle() || !handles.erase(entity->sourceHandle())) entity->clearDwgProvenance(RS_Entity::Identity);
        if (entity->rtti() == RS2::EntityInsert || entity->ownerLineage()) {
            const auto original = entity->lineage(); const auto number = ++copies[original];
            if (!lineages.erase(original)) {
                entity->setLineage(copied(original, number));
                if (entity->ownerLineage()) entity->setOwnerLineage(copied(entity->ownerLineage(), number));
            }
        }
    }
    auto publication = LC_OffsetCurvePublication::prepareCreation(*m_document, *m_viewport, batch.entitiesToDelete,
        batch.entitiesToAdd, {}, batch.entitiesToDelete, work->inputs->roots());
    if (!publication || !alive || !currentNativeTrim(work) || !publication->commit()) {
        if (alive) { cancelNativeTrim(); if (currentTrimContext()) commandMessage(tr("Trim inputs changed before publication; nothing changed")); }
        return;
    }
    for (auto& owner : owners) owner.release();
    m_actionData->demoted = result.nativeDemotions;
    m_actionData->undoEpoch = work->epoch + 1;
    m_actionData->guard->stop(); m_actionData->work.reset();
    publication->notify();
    if (!alive) return;
    if (!currentTrimContext()) { abandonTrimContext(true); return; }
    m_viewport->notifyChanged();
    if (!alive || !currentTrimContext()) return;
    doTriggerCompletion(true);
    if (alive && currentTrimContext()) { drawSnapper(); m_graphicView->redraw(); }
}

void LC_ActionModifyTrim::trigger() {
    // Check before the base opens an undo section or dereferences retained picks.
    if (m_actionData->triggerAdmissionEpoch) return;
    if (!validateCapturedTrimInputs()) return;
    if (hasPendingNativeTrim()) return;
    if (m_trimEntity && m_limitEntity &&
        (m_trimEntity->rtti() == RS2::EntityOffsetCurve || m_limitEntity->rtti() == RS2::EntityOffsetCurve)) {
        const QPointer<LC_ActionModifyTrim> alive(this);
        deletePreview(); deleteInfoCursor(); deleteHighlights(); deleteSnapper();
        if (alive && currentTrimContext()) beginNativeTrim();
        return;
    }
    if (m_trimEntity && m_limitEntity &&
        (m_trimEntity->rtti() == RS2::EntitySpline || (m_both && m_limitEntity->rtti() == RS2::EntitySpline)) &&
        m_trimEntity->rtti() != RS2::EntityOffsetCurve && m_limitEntity->rtti() != RS2::EntityOffsetCurve) {
        commandMessage(tr("Trim refused: normalized spline replacement requires an offset curve partner; nothing changed"));
        return;
    }
    const auto admitted = m_document->undoStateEpoch();
    if (admitted == std::numeric_limits<std::uint64_t>::max()) {
        commandMessage(tr("Trim refused: undo history epoch limit reached; nothing changed"));
        return;
    }
    m_actionData->triggerAdmissionEpoch = admitted;
    const auto clearAdmission = qScopeGuard([this] { m_actionData->triggerAdmissionEpoch.reset(); });
    // Keep the inherited undo transaction, but do not use the preview base's
    // unconditional post-doTrigger drawing after an end-cycle listener runs.
    deletePreview(); deleteInfoCursor(); deleteHighlights(); deleteSnapper();
    if (!validateCapturedTrimInputs()) return;
    if (doCheckMayTrigger()) doTrigger();
    if (!currentTrimContext()) { abandonTrimContext(true); return; }
    drawSnapper();
    m_graphicView->redraw();
}

bool LC_ActionModifyTrim::doTriggerModifications(LC_DocumentModificationBatch& ctx) {
    if (m_actionData->triggerAdmissionEpoch) {
        if (!currentTrimContext()) { abandonTrimContext(true); return false; }
        const auto admitted = *m_actionData->triggerAdmissionEpoch;
        // LC_UndoSection opens exactly one cycle between public trigger and
        // this callback. Only that single increment belongs to this attempt.
        if (m_actionData->undoEpoch != admitted || m_document->undoStateEpoch() != admitted + 1) {
            commandMessage(tr("Trim refused: undo history changed during the attempt; nothing changed"));
            return false;
        }
        m_actionData->undoEpoch = admitted + 1;
    }
    if (!validateCapturedTrimInputs()) return false;
    m_actionData->demoted = 0;
    const bool nativePair = (m_trimEntity && m_trimEntity->rtti() == RS2::EntityOffsetCurve) ||
        (m_limitEntity && m_limitEntity->rtti() == RS2::EntityOffsetCurve);
    if (isTrimTarget(m_trimEntity, nativePair) && m_limitEntity != nullptr && (!m_both || isTrimTarget(m_limitEntity, nativePair))) {
        if (m_trimEntity->rtti() == RS2::EntityOffsetCurve || m_limitEntity->rtti() == RS2::EntityOffsetCurve) {
            const auto result = RS_Modification::trimStoredCache(*m_document, *m_trimEntity, m_actionData->trimCoord,
                *m_limitEntity, m_actionData->limitCoord, m_both, ctx, storedCacheTrimOptions());
            if (!result.result) {
                QString reason;
                using Refusal = LC_OffsetCacheTrim::Refusal;
                switch (result.cacheRefusal.value_or(Refusal::InvalidInput)) {
                case Refusal::NoUsableRoots: reason = tr("no usable intersections"); break;
                case Refusal::AmbiguousPick: reason = tr("ambiguous picked interval"); break;
                case Refusal::AmbiguousRoots: case Refusal::TangencyOrOverlap: reason = tr("uncertain, tangent or overlapping intersections"); break;
                case Refusal::LimitExceeded: reason = tr("work or output limit reached"); break;
                case Refusal::Cancelled: reason = tr("cancelled"); break;
                case Refusal::UnsupportedLayout: reason = tr("target is locked, hidden, stale or unsupported"); break;
                case Refusal::UnsupportedCutter: reason = tr("unsupported limiting geometry"); break;
                case Refusal::AllocationFailure: reason = tr("not enough memory"); break;
                default: reason = tr("invalid or unresolved geometry"); break;
                }
                commandMessage(tr("Offset cache trim refused: %1; nothing changed").arg(reason));
            } else m_actionData->demoted = result.nativeDemotions;
            return result.result;
        }
        auto* atomic = dynamic_cast<RS_AtomicEntity*>(m_trimEntity);
        if (!atomic) return false;
        const LC_TrimResult trimResult = RS_Modification::trim(m_actionData->trimCoord, atomic, m_actionData->limitCoord,
                                                               m_limitEntity, m_both, ctx);

        if (trimResult.trimmed1 != nullptr) {
            // trim() may swap its inputs; the batch records the actual replacement source.
            const RS_Entity* trimmedSource = ctx.entitiesToDelete.first();
            trimResult.trimmed1->setPen(trimmedSource->getPen(false));
            trimResult.trimmed1->setLayer(trimmedSource->getLayer(false));

            if (m_both) {
                if (trimResult.trimmed2 != nullptr) {
                    trimResult.trimmed2->setPen(m_limitEntity->getPen(false));
                    trimResult.trimmed2->setLayer(m_limitEntity->getLayer(false));
                }
            }
            ctx.dontSetActiveLayerAndPen();
            return trimResult.result;
        }
        return false;
    }
    return false;
}

void LC_ActionModifyTrim::doTriggerCompletion(const bool success) {
    if (!currentTrimContext()) { abandonTrimContext(true); return; }
    // endUndoCycle notifies observers before returning here. An observer may
    // have performed an external undo/redo: never restamp it as our own epoch.
    if (m_actionData->undoEpoch != m_document->undoStateEpoch()) {
        validateCapturedTrimInputs();
        return;
    }
    if (success) {
        if (m_actionData->demoted) commandMessage(tr("Trim converted %1 offset curve(s) to ordinary splines").arg(qulonglong(m_actionData->demoted)));
        m_trimEntity = nullptr;
        m_actionData->trimId = 0;
        if (m_both) {
            setLimitEntity(nullptr);
            setStatus(ChooseLimitEntity);
        }
        else {
            setStatus(ChooseTrimEntity);
        }
    }
}

void LC_ActionModifyTrim::previewTrim(RS_Entity* entityToTrimCandidate, RS_Entity* limitingEntity, const RS_Vector& trimCoordinates,
                                      const RS_Vector& limitCoordinates, bool& trimInvalid) const {
    entityToTrimCandidate = nativeLimitOwner(entityToTrimCandidate);
    limitingEntity = nativeLimitOwner(limitingEntity);
    if (entityToTrimCandidate && limitingEntity && entityToTrimCandidate != limitingEntity &&
        (entityToTrimCandidate->rtti() == RS2::EntityOffsetCurve || limitingEntity->rtti() == RS2::EntityOffsetCurve)) {
        LC_DocumentModificationBatch prepared;
        const auto result = RS_Modification::trimStoredCache(*m_document, *entityToTrimCandidate, trimCoordinates,
            *limitingEntity, limitCoordinates, m_both, prepared, storedCacheTrimOptions());
        if (!result.result) return;
        trimInvalid = false;
        // The fresh preparation is identical to commit, but only private
        // outputs enter the owning preview. Originals/selection stay untouched.
        std::array<std::unique_ptr<RS_Entity>, 4> owned;
        for (qsizetype i = 0; i < prepared.entitiesToAdd.size(); ++i) owned[std::size_t(i)].reset(prepared.entitiesToAdd[i]);
        for (auto& e : owned) if (e) { m_preview->addEntity(e.get()); e.release(); }
        if (m_showRefEntitiesOnPreview) {
            if (result.intersection1.valid) previewRefPoint(result.intersection1);
            if (result.intersection2.valid) previewRefPoint(result.intersection2);
        }
        highlightHover(entityToTrimCandidate);
        return;
    }
    if (limitingEntity != nullptr && entityToTrimCandidate != limitingEntity) {
        if (isTrimTarget(entityToTrimCandidate) && (!m_both || isTrimTarget(limitingEntity))) {
            auto* atomicTrimCandidate = dynamic_cast<RS_AtomicEntity*>(entityToTrimCandidate);

            LC_DocumentModificationBatch ctx;
            const LC_TrimResult trimResult = RS_Modification::trim(trimCoordinates, atomicTrimCandidate, limitCoordinates, limitingEntity,
                                                                   m_both, ctx);
            // trim() hands back new entities, and the batch it filled in is a local that frees
            // nothing, so what the preview does not take is released below
            bool previewOwnsTrimmed1 = false;
            bool previewOwnsTrimmed2 = false;
            if (trimResult.result) {
                trimInvalid = false;
                const RS_Entity* trimmedSource = ctx.entitiesToDelete.first();
                highlightHover(trimmedSource);
                if (m_showRefEntitiesOnPreview) {
                    previewRefPoint(trimResult.intersection1);
                    previewOwnsTrimmed1 = previewRefTrimmedEntity(trimResult.trimmed1, trimmedSource);
                    if (trimResult.intersection2.valid) {
                        previewRefPoint(trimResult.intersection2);
                    }
                    if (m_both) {
                        if (trimResult.trimmed2 != nullptr) {
                            previewOwnsTrimmed2 = previewRefTrimmedEntity(trimResult.trimmed2, limitingEntity);
                        }
                    }
                    if (isInfoCursorForModificationEnabled()) {
                        const auto msg = rtti() == RS2::ActionModifyTrim2 ? tr("Trim Two") : tr("Trim");
                        auto builder = msgStart().string(msg).vector(tr("Intersection:"), trimResult.intersection1);
                        if (trimResult.intersection2.valid) {
                            builder.vector(tr("Intersection 2:"), trimResult.intersection2);
                        }
                        builder.toInfoCursorZone2(false);
                    }
                }
            }
            if (!previewOwnsTrimmed1) {
                delete trimResult.trimmed1;
            }
            if (!previewOwnsTrimmed2) {
                delete trimResult.trimmed2;
            }
        }
    }
}

void LC_ActionModifyTrim::onMouseMoveEvent(const int status, const LC_MouseEvent* e) {
    if (hasPendingNativeTrim()) return;
    if (!validateCapturedTrimInputs()) return;
    const RS_Vector mouse = e->graphPoint;
    bool trimInvalid = true;
    switch (status) {
        case ChooseLimitEntity: {
            RS_Entity* se = catchLimitEntity(e);
            if (se != nullptr) {
                prepareEntityDescription(se, RS2::EntityDescriptionLevel::DescriptionCatched);
            }
            if (m_trimEntity != nullptr && se != nullptr) {
                previewTrim(m_trimEntity, se, m_actionData->trimCoord, mouse, trimInvalid);
                if (trimInvalid) {
                    highlightSelected(m_trimEntity);
                }
            }
            else if (se != nullptr) {
                highlightHover(se);
            }

            break;
        }
        case ChooseTrimEntity: {
            RS_Entity* entityToTrimCandidate = catchAndDescribe(e, RS2::ResolveNone);
            previewTrim(entityToTrimCandidate, m_limitEntity, mouse, m_actionData->limitCoord, trimInvalid);
            if (trimInvalid) {
                highlightSelected(m_limitEntity);
            }
            break;
        }
        default:
            break;
    }
}

void LC_ActionModifyTrim::onMouseLeftButtonRelease(const int status, const LC_MouseEvent* e) {
    if (hasPendingNativeTrim()) return;
    if (!validateCapturedTrimInputs()) return;
    const RS_Vector mouse = e->graphPoint;
    switch (status) {
        case ChooseLimitEntity: {
            RS_Entity* se = catchLimitEntity(e);
            if (se != nullptr) {
                setLimitEntity(se);
                m_actionData->limitCoord = mouse;
                if (m_trimEntity != nullptr) {
                    trigger();
                }
                else {
                    setStatus(ChooseTrimEntity);
                }
            }
            break;
        }
        case ChooseTrimEntity: {
            RS_Entity* se = nativeLimitOwner(catchEntityByEvent(e, RS2::ResolveNone));
            if (isTrimTarget(se, m_limitEntity && m_limitEntity->rtti() == RS2::EntityOffsetCurve) && se != m_limitEntity) {
                m_actionData->trimCoord = mouse;
                m_trimEntity = se;
                m_actionData->trimId = se->getId();
                trigger();
            }
            break;
        }
        default:
            break;
    }
}

void LC_ActionModifyTrim::onMouseRightButtonRelease(const int status, [[maybe_unused]] const LC_MouseEvent* e) {
    cancelNativeTrim();
    if (!currentTrimContext()) { abandonTrimContext(true); return; }
    deletePreview();
    initPrevious(status);
}

void LC_ActionModifyTrim::updateActionPrompt() {
    switch (getStatus()) {
        case ChooseLimitEntity:
            if (m_both) {
                updatePromptTRCancel(tr("Select first trim entity"));
            }
            else {
                updatePromptTRBack(tr("Select limiting entity"));
            }
            break;
        case ChooseTrimEntity:
            if (m_both) {
                updatePromptTRCancel(tr("Select second trim entity"));
            }
            else {
                updatePromptTRBack(tr("Select entity to trim"));
            }
            break;
        default:
            updatePrompt();
            break;
    }
}

RS2::CursorType LC_ActionModifyTrim::doGetMouseCursor([[maybe_unused]] int status) {
    return RS2::SelectCursor;
}

LC_StoredCacheTrimOptions LC_ActionModifyTrim::storedCacheTrimOptions() const { return {}; }

bool LC_ActionModifyTrim::hasNativeTrimPartner() const {
    // Enable a pending plain-cache first pick only in a native-capable drawing.
    // Final dispatch still REQUIRES a native operand; ordinary-only Trim retains
    // its existing atomic contract, including rejecting spline display children.
    if (!currentTrimContext()) return false;
    for (const auto* entity : *m_document) if (entity && entity->getParent() == m_document &&
        entity->rtti() == RS2::EntityOffsetCurve && !entity->isDeleted() && entity->isVisible()) return true;
    return false;
}

/**
 * @return whether the preview took the trimmed entity; if not, it is the caller's to release
 */
bool LC_ActionModifyTrim::previewRefTrimmedEntity(RS_Entity* trimmed, const RS_Entity* original) const {
    const int rtti = trimmed->rtti();
    switch (rtti) {
        case RS2::EntityLine: {
            RS_Vector start = original->getStartpoint();
            const RS_Vector startTrimmed = trimmed->getStartpoint();
            RS_Vector end = original->getEndpoint();
            const RS_Vector endTrimmed = trimmed->getEndpoint();
            const bool sameStart = start == startTrimmed;
            const bool sameEnd = end == endTrimmed;

            if (!sameStart) {
                end = startTrimmed;
            }
            if (!sameEnd) {
                start = endTrimmed;
            }
            previewRefLine(start, end);
            break;
        }
        case RS2::EntityArc: {
            auto* arc = static_cast<RS_Arc*>(trimmed);
            if (arc == nullptr) {
                break;
            }
            RS_ArcData data = arc->getData();
            data.reversed = !data.reversed;
            previewRefArc(data);
            break;
        }
        case RS2::EntityCircle: {
            // that's really strange case - not trimmed circle???
            //            auto* circle = dynamic_cast<RS_Circle*>(trimmed);
            //            previewRefCircle(circle->getCenter(), circle->getRadius());
            break;
        }
        case RS2::EntityEllipse: {
            const auto* ellipse = static_cast<RS_Ellipse*>(trimmed);
            if (ellipse == nullptr) {
                break;
            }
            auto data = ellipse->getData();
            data.reversed = !data.reversed;
            previewRefEllipse(data);
            break;
        }
        case RS2::EntityParabola:{
          // Parabola has no reversed-direction toggle; just preview the
          // resulting (already-trimmed) entity.
          previewEntity(trimmed);
          return true;
        }
        default: {
            previewEntity(trimmed);
            RS_DEBUG->print("RS_ActionModifyTrim::unhandled trimmed entity type");
            return true;
        }
    }
    return false;
}
